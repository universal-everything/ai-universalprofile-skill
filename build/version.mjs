// The skill's version, in one place. Semantic Versioning (README "Versioning and releases"):
// package.json "version" is canonical; every other copy is written by `set` / `release` and checked by `check`.
//
//   node build/version.mjs check                       every copy agrees (run by build.mjs and verify-skill.mjs)
//   node build/version.mjs check --release --tag vX.Y.Z also: the CHANGELOG entry is dated and the tag matches (release.yml)
//   node build/version.mjs set <major|minor|patch|X.Y.Z>  bump every copy (then: npm run build && node build/gen-verb-docs.mjs)
//   node build/version.mjs release --date YYYY-MM-DD     date the CHANGELOG entry of the current version (never in the future)
//
// Copies: package-lock.json (root "version" and packages[""].version only), SKILL.md metadata.version,
// platforms/openai/plugin.json, the generated version blocks of README.md and skills/universal-profile/README.md,
// the newest CHANGELOG heading, and (built) scripts/BUILD.json and the bundle banners. The bundled data has its own
// data-version in SKILL.md, independent of this version.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const DASH = String.fromCharCode(0x2014); // CHANGELOG headings: "## [0.2.0] — 2026-10-23"
const SEMVER = /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/;
const START = "<!-- version:start (generated by build/version.mjs; do not edit by hand) -->";
const END = "<!-- version:end -->";

export const FILES = {
  pkg: "package.json",
  lock: "package-lock.json",
  skill: "skills/universal-profile/SKILL.md",
  plugin: "skills/universal-profile/platforms/openai/plugin.json",
  changelog: "skills/universal-profile/CHANGELOG.md",
  skillReadme: "skills/universal-profile/README.md",
  sourceReadme: "README.md",
  build: "skills/universal-profile/scripts/BUILD.json",
};
/** Every shipped bundle (each .mjs file under scripts/, also chunks added later), relative to the skill folder: each banner names the version. */
function bundles(root) {
  const skillDir = join(root, "skills", "universal-profile");
  const walk = (d) => (existsSync(d) ? readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(d, e.name)) : e.name.endsWith(".mjs") ? [join(d, e.name)] : [])) : []);
  return walk(join(skillDir, "scripts")).map((f) => relative(skillDir, f).split(sep).join("/")).sort();
}

const read = (root, f) => readFileSync(join(root, f), "utf8");
const write = (root, f, text) => writeFileSync(join(root, f), text);

function parse(v) {
  const m = SEMVER.exec(v ?? "");
  return m ? m.slice(1).map(Number) : null;
}
function compare(a, b) {
  const x = parse(a);
  const y = parse(b);
  for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return x[i] - y[i];
  return 0;
}
const today = (now = new Date()) => now.toISOString().slice(0, 10);

/** Every "## [X.Y.Z] — Unreleased|YYYY-MM-DD" heading of the CHANGELOG, newest first. */
export function changelogEntries(text) {
  const re = new RegExp(`^## \\[([^\\]]+)\\] ${DASH} (Unreleased|\\d{4}-\\d{2}-\\d{2})\\b`, "gm");
  return [...text.matchAll(re)].map((m) => ({ version: m[1], status: m[2], index: m.index, heading: m[0] }));
}

function skillVersion(text) {
  const fm = /^---\n([\s\S]*?)\n---\n/.exec(text);
  const meta = fm && /^metadata:\n((?:[ ]+.*\n?)*)/m.exec(fm[1]);
  const m = meta && /^ {2}version: "([^"]*)"$/m.exec(meta[1]);
  const d = meta && /^ {2}data-version: "([^"]*)"$/m.exec(meta[1]);
  return { version: m ? m[1] : null, dataVersion: d ? d[1] : null };
}

export function renderSkillReadmeBlock(version, status) {
  return `${START}\n**Version ${version}** (${status === "Unreleased" ? "not released yet" : `released ${status}`}) · [What's new](CHANGELOG.md) · [How versions work](#versions)\n${END}`;
}

export function renderSourceReadmeBlock(version, status, dataVersion) {
  return `${START}\nCurrent version: **${version}** (${status === "Unreleased" ? "not released yet" : `released ${status}`}); changelog: [\`skills/universal-profile/CHANGELOG.md\`](skills/universal-profile/CHANGELOG.md); bundled data: \`data-version\` ${dataVersion ?? "?"} in \`SKILL.md\` (separate from the version).\n${END}`;
}

function block(text) {
  const a = text.indexOf(START);
  const b = text.indexOf(END);
  return a >= 0 && b > a ? text.slice(a, b + END.length) : null;
}
function replaceBlock(text, rendered) {
  const current = block(text);
  if (!current) throw new Error("version block markers missing");
  return text.replace(current, rendered);
}

/** The canonical version (package.json). */
export function currentVersion(root) {
  return JSON.parse(read(root, FILES.pkg)).version;
}

/** Problems found (empty = consistent). `built` also checks BUILD.json and the bundles; `release` the dated entry and `tag`. */
export function checkVersion(root, { built = true, release = false, tag, now = new Date() } = {}) {
  const problems = [];
  const v = currentVersion(root);
  if (!parse(v)) return [`package.json version "${v}" is not X.Y.Z`];

  const lock = JSON.parse(read(root, FILES.lock));
  if (lock.version !== v) problems.push(`${FILES.lock}: root version ${lock.version} (expected ${v})`);
  if (lock.packages?.[""]?.version !== v) problems.push(`${FILES.lock}: packages[""].version ${lock.packages?.[""]?.version} (expected ${v})`);

  const skill = skillVersion(read(root, FILES.skill));
  if (skill.version !== v) problems.push(`${FILES.skill}: metadata.version ${skill.version} (expected ${v})`);
  if (!skill.dataVersion) problems.push(`${FILES.skill}: metadata.data-version missing`);

  const plugin = JSON.parse(read(root, FILES.plugin));
  if (plugin.version !== v) problems.push(`${FILES.plugin}: version ${plugin.version} (expected ${v})`);

  const entries = changelogEntries(read(root, FILES.changelog));
  const top = entries[0];
  if (!top) problems.push(`${FILES.changelog}: no "## [X.Y.Z] ${DASH} Unreleased|YYYY-MM-DD" heading`);
  else {
    if (top.version !== v) problems.push(`${FILES.changelog}: newest entry is ${top.version} (expected ${v})`);
    for (const [i, e] of entries.entries()) {
      if (!parse(e.version)) problems.push(`${FILES.changelog}: "${e.version}" is not X.Y.Z`);
      else if (i > 0 && parse(entries[i - 1].version) && compare(entries[i - 1].version, e.version) <= 0) problems.push(`${FILES.changelog}: ${entries[i - 1].version} must be newer than the entry below it (${e.version})`);
      if (i > 0 && e.status === "Unreleased") problems.push(`${FILES.changelog}: only the newest entry may be Unreleased (${e.version})`);
      if (e.status !== "Unreleased" && Number.isNaN(Date.parse(`${e.status}T00:00:00Z`))) problems.push(`${FILES.changelog}: ${e.version} has an invalid date ${e.status}`);
    }
    if (release) {
      if (top.status === "Unreleased") problems.push(`${FILES.changelog}: ${v} is not dated (run: node build/version.mjs release --date YYYY-MM-DD)`);
      else if (top.status > today(now)) problems.push(`${FILES.changelog}: ${v} is dated in the future (${top.status})`);
      const previous = entries.slice(1).find((e) => e.status !== "Unreleased");
      if (previous && top.status !== "Unreleased" && top.status < previous.status) problems.push(`${FILES.changelog}: ${v} (${top.status}) is dated before ${previous.version} (${previous.status})`);
    }
  }
  if (tag !== undefined && tag !== `v${v}`) problems.push(`tag ${tag} does not match the version (expected v${v})`);

  const status = top?.status ?? "Unreleased";
  const skillReadmeText = read(root, FILES.skillReadme);
  const skillReadme = block(skillReadmeText);
  if (skillReadme !== renderSkillReadmeBlock(v, status)) problems.push(`${FILES.skillReadme}: version block ${skillReadme ? "out of date" : "missing"} (run: node build/version.mjs set ${v})`);
  if (!skillReadmeText.includes(`\n- **${v}** (`)) problems.push(`${FILES.skillReadme}: the release history ("Versions") has no line "- **${v}** (…): what is new"`);
  const sourceReadme = block(read(root, FILES.sourceReadme));
  if (sourceReadme !== renderSourceReadmeBlock(v, status, skill.dataVersion)) problems.push(`${FILES.sourceReadme}: version block ${sourceReadme ? "out of date" : "missing"} (run: node build/version.mjs set ${v})`);

  if (built) {
    const buildJson = join(root, FILES.build);
    if (!existsSync(buildJson)) problems.push(`${FILES.build} missing (run: npm run build)`);
    else if (JSON.parse(readFileSync(buildJson, "utf8")).version !== v) problems.push(`${FILES.build}: version ${JSON.parse(readFileSync(buildJson, "utf8")).version} (expected ${v}; run: npm run build)`);
    for (const b of bundles(root)) {
      const f = join(root, "skills", "universal-profile", b);
      const m = /Universal Profile Agent Skill v(\S+) /.exec(readFileSync(f, "utf8").slice(0, 2000));
      if (!m || m[1] !== v) problems.push(`skills/universal-profile/${b}: built as v${m ? m[1] : "?"} (expected ${v}; run: npm run build)`);
    }
  }
  return problems;
}

function bump(v, kind) {
  if (parse(kind)) {
    if (compare(kind, v) <= 0) throw new Error(`the new version ${kind} must be greater than ${v}`);
    return kind;
  }
  const [maj, min, pat] = parse(v);
  if (kind === "major") return `${maj + 1}.0.0`;
  if (kind === "minor") return `${maj}.${min + 1}.0`;
  if (kind === "patch") return `${maj}.${min}.${pat + 1}`;
  throw new Error(`unknown bump "${kind}" (major, minor, patch or X.Y.Z)`);
}

/** Sets every copy of the version (not the built files: run npm run build afterwards). Returns { from, to }. */
export function setVersion(root, kind) {
  const from = currentVersion(root);
  const to = bump(from, kind);
  const once = (text, pattern, replacement, what) => {
    const n = text.split(pattern).length - 1;
    if (n < 1) throw new Error(`${what}: "${pattern}" not found`);
    return text.replace(pattern, replacement);
  };

  write(root, FILES.pkg, once(read(root, FILES.pkg), `"version": "${from}"`, `"version": "${to}"`, FILES.pkg));

  // lockfile: only the root entries (the first two "version" lines); every dependency stays byte for byte
  const lockText = read(root, FILES.lock);
  const before = JSON.parse(lockText);
  let seen = 0;
  const lockNext = lockText.replace(new RegExp(`"version": "${from.replace(/\./g, "\\.")}"`, "g"), (m) => (++seen <= 2 ? `"version": "${to}"` : m));
  const after = JSON.parse(lockNext);
  if (after.version !== to || after.packages?.[""]?.version !== to) throw new Error(`${FILES.lock}: the root version entries were not where expected`);
  before.version = to;
  before.packages[""].version = to;
  if (JSON.stringify(before) !== JSON.stringify(after)) throw new Error(`${FILES.lock}: refusing to change anything but the root version`);
  write(root, FILES.lock, lockNext);

  const skillText = read(root, FILES.skill);
  if (skillVersion(skillText).version !== from) throw new Error(`${FILES.skill}: metadata.version is not ${from}; fix it first`);
  write(root, FILES.skill, once(skillText, `\n  version: "${from}"\n`, `\n  version: "${to}"\n`, FILES.skill));

  write(root, FILES.plugin, once(read(root, FILES.plugin), `"version": "${from}"`, `"version": "${to}"`, FILES.plugin));

  let log = read(root, FILES.changelog);
  const top = changelogEntries(log)[0];
  if (top && top.status === "Unreleased") log = log.replace(top.heading, `## [${to}] ${DASH} Unreleased`);
  else {
    const at = top ? top.index : log.length;
    log = `${log.slice(0, at)}## [${to}] ${DASH} Unreleased\n\n### Added\n\n### Changed\n\n### Fixed\n\n${log.slice(at)}`;
  }
  write(root, FILES.changelog, log);

  writeBlocks(root, to, "Unreleased");
  return { from, to };
}

function writeBlocks(root, version, status) {
  const { dataVersion } = skillVersion(read(root, FILES.skill));
  write(root, FILES.skillReadme, replaceBlock(read(root, FILES.skillReadme), renderSkillReadmeBlock(version, status)));
  write(root, FILES.sourceReadme, replaceBlock(read(root, FILES.sourceReadme), renderSourceReadmeBlock(version, status, dataVersion)));
}

/** Dates the CHANGELOG entry of the current version (the day it is published) and the README blocks. */
export function releaseVersion(root, date, { now = new Date() } = {}) {
  const v = currentVersion(root);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date ?? "") || Number.isNaN(Date.parse(`${date}T00:00:00Z`))) throw new Error(`--date must be YYYY-MM-DD (got ${date})`);
  if (date > today(now)) throw new Error(`--date ${date} is in the future; date a release on the day it is published`);
  const log = read(root, FILES.changelog);
  const entries = changelogEntries(log);
  const top = entries[0];
  if (!top || top.version !== v || top.status !== "Unreleased") throw new Error(`${FILES.changelog}: the newest entry must be "## [${v}] ${DASH} Unreleased"`);
  const previous = entries.slice(1).find((e) => e.status !== "Unreleased");
  if (previous && date < previous.status) throw new Error(`--date ${date} is before the previous release ${previous.version} (${previous.status})`);
  write(root, FILES.changelog, log.replace(top.heading, `## [${v}] ${DASH} ${date}`));
  writeBlocks(root, v, date);
  const readme = read(root, FILES.skillReadme);
  if (readme.includes(`\n- **${v}** (unreleased)`)) write(root, FILES.skillReadme, readme.replace(`\n- **${v}** (unreleased)`, `\n- **${v}** (${date})`));
  return { version: v, date };
}

function main(argv) {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const [cmd, ...rest] = argv;
  const opt = (name) => {
    const i = rest.indexOf(`--${name}`);
    return i >= 0 ? rest[i + 1] : undefined;
  };
  try {
    if (cmd === "check") {
      const problems = checkVersion(root, { release: rest.includes("--release"), tag: opt("tag"), built: !rest.includes("--source-only") });
      if (problems.length) {
        for (const p of problems) console.error(`✗ ${p}`);
        return 1;
      }
      console.log(`✓ version ${currentVersion(root)} is consistent${rest.includes("--release") ? " and ready to release" : ""}`);
      return 0;
    }
    if (cmd === "set") {
      const { from, to } = setVersion(root, rest[0]);
      console.log(`version ${from} → ${to}: package.json, package-lock.json (root only), SKILL.md, plugin.json, CHANGELOG.md (Unreleased entry) and both README version blocks`);
      console.log(`next: describe the changes in skills/universal-profile/CHANGELOG.md, add "- **${to}** (unreleased): …" to the release history in skills/universal-profile/README.md, then npm run build && node build/gen-verb-docs.mjs && npm run verify:skill`);
      return 0;
    }
    if (cmd === "release") {
      const r = releaseVersion(root, opt("date"));
      console.log(`CHANGELOG ${r.version} dated ${r.date}; commit, push source, then publish (npm run publish:main -- --push or tag v${r.version})`);
      return 0;
    }
    console.error("usage: node build/version.mjs check [--release] [--tag vX.Y.Z] | set <major|minor|patch|X.Y.Z> | release --date YYYY-MM-DD");
    return 2;
  } catch (e) {
    console.error(`✗ ${e.message}`);
    return 1;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) process.exitCode = main(process.argv.slice(2));
